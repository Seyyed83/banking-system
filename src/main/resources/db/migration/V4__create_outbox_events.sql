-- V4: transactional outbox. Rows are inserted in the SAME Oracle transaction that finalizes a
-- transaction request, so an event exists if and only if the money movement / final failure committed.
-- A separate publisher (added later) reads PENDING rows and hands them to the message broker.
CREATE TABLE OUTBOX_EVENTS (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    EVENT_ID        VARCHAR2(36 CHAR)   NOT NULL,
    AGGREGATE_TYPE  VARCHAR2(50 CHAR)   NOT NULL,
    AGGREGATE_ID    VARCHAR2(100 CHAR)  NOT NULL,
    EVENT_TYPE      VARCHAR2(100 CHAR)  NOT NULL,
    PAYLOAD         CLOB                NOT NULL,
    STATUS          VARCHAR2(20 CHAR)   DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_COUNT   NUMBER(10)          DEFAULT 0 NOT NULL,
    PUBLISHER_ID    VARCHAR2(100 CHAR),
    LEASE_UNTIL     TIMESTAMP WITH TIME ZONE,
    NEXT_ATTEMPT_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    PUBLISHED_AT    TIMESTAMP WITH TIME ZONE,
    LAST_ERROR      VARCHAR2(1000 CHAR),

    CONSTRAINT PK_OUTBOX_EVENTS PRIMARY KEY (ID),
    CONSTRAINT UQ_OUTBOX_EVENT_ID UNIQUE (EVENT_ID),
    -- at most one final event of each type per aggregate (e.g. one TRANSACTION_COMPLETED per request)
    CONSTRAINT UQ_OUTBOX_AGGREGATE_EVENT UNIQUE (AGGREGATE_TYPE, AGGREGATE_ID, EVENT_TYPE),
    CONSTRAINT CK_OUTBOX_STATUS CHECK (STATUS IN ('PENDING', 'PROCESSING', 'PUBLISHED', 'FAILED')),
    CONSTRAINT CK_OUTBOX_ATTEMPTS CHECK (ATTEMPT_COUNT >= 0)
);

-- Publisher polling: oldest PENDING rows that are due.
CREATE INDEX IDX_OUTBOX_STATUS_NEXT
    ON OUTBOX_EVENTS (STATUS, NEXT_ATTEMPT_AT, ID);
