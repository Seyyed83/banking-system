-- V5: audit log of integration events consumed from Kafka.
-- UNIQUE(EVENT_ID) makes the consumer idempotent: Kafka delivers at least once, so the same
-- event may arrive twice and must be recorded only once.
CREATE TABLE TRANSACTION_EVENT_LOG (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    EVENT_ID     VARCHAR2(36 CHAR)  NOT NULL,
    EVENT_TYPE   VARCHAR2(100 CHAR) NOT NULL,
    AGGREGATE_ID VARCHAR2(100 CHAR) NOT NULL,
    PAYLOAD      CLOB               NOT NULL,
    RECEIVED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_TRANSACTION_EVENT_LOG PRIMARY KEY (ID),
    CONSTRAINT UQ_EVENT_LOG_EVENT_ID UNIQUE (EVENT_ID)
);

CREATE INDEX IDX_EVENT_LOG_AGGREGATE
    ON TRANSACTION_EVENT_LOG (AGGREGATE_ID);
