
-- 1. Customers
CREATE TABLE CUSTOMERS (
                           ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                           CUSTOMER_TYPE       VARCHAR2(20 CHAR) NOT NULL,
                           IDENTITY_TYPE       VARCHAR2(30 CHAR) NOT NULL,
                           IDENTITY_NUMBER     VARCHAR2(50 CHAR) NOT NULL,
                           FULL_NAME           VARCHAR2(200 CHAR) NOT NULL,
                           BIRTH_OR_REG_DATE   DATE,
                           MOBILE              VARCHAR2(20 CHAR),
                           ADDRESS             VARCHAR2(500 CHAR),
                           POSTAL_CODE         VARCHAR2(20 CHAR),
                           CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                           CONSTRAINT PK_CUSTOMERS PRIMARY KEY (ID),
                           CONSTRAINT UQ_CUSTOMER_IDENTITY UNIQUE (IDENTITY_TYPE, IDENTITY_NUMBER),
                           CONSTRAINT CK_CUSTOMER_TYPE
                               CHECK (CUSTOMER_TYPE IN ('INDIVIDUAL', 'CORPORATE', 'FOREIGN'))
);

-- 2. Accounts
CREATE TABLE ACCOUNTS (
                          ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                          ACCOUNT_NUMBER  VARCHAR2(14 CHAR) NOT NULL,
                          CUSTOMER_ID     NUMBER(19),
                          ACCOUNT_ROLE    VARCHAR2(20 CHAR) NOT NULL,
                          STATUS          VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
                          BALANCE         NUMBER(19,4) DEFAULT 0 NOT NULL,
                          CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                          UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                          CONSTRAINT PK_ACCOUNTS PRIMARY KEY (ID),
                          CONSTRAINT UQ_ACCOUNT_NUMBER UNIQUE (ACCOUNT_NUMBER),
                          CONSTRAINT FK_ACCOUNT_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
                              REFERENCES CUSTOMERS(ID),
                          CONSTRAINT CK_ACCOUNT_NUMBER_LENGTH CHECK (LENGTH(ACCOUNT_NUMBER) = 14),
                          CONSTRAINT CK_ACCOUNT_ROLE CHECK (ACCOUNT_ROLE IN ('CUSTOMER', 'SYSTEM')),
                          CONSTRAINT CK_ACCOUNT_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'BLOCKED')),
                          CONSTRAINT CK_ACCOUNT_BALANCE CHECK (BALANCE >= 0),
                          CONSTRAINT CK_ACCOUNT_OWNER CHECK (
                              (ACCOUNT_ROLE = 'CUSTOMER' AND CUSTOMER_ID IS NOT NULL)
                                  OR
                              (ACCOUNT_ROLE = 'SYSTEM' AND CUSTOMER_ID IS NULL)
                              )
);

-- 3. Transaction requests
CREATE TABLE TRANSACTION_REQUESTS (
                                      ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                                      REQUEST_CODE        VARCHAR2(64 CHAR) NOT NULL,
                                      CLIENT_ID           VARCHAR2(100 CHAR) NOT NULL,
                                      IDEMPOTENCY_KEY     VARCHAR2(100 CHAR) NOT NULL,
                                      TRANSACTION_TYPE    VARCHAR2(20 CHAR) NOT NULL,
                                      SOURCE_ACCOUNT_ID   NUMBER(19),
                                      DESTINATION_ACCOUNT_ID NUMBER(19),
                                      AMOUNT              NUMBER(19,4) NOT NULL,
                                      STATUS              VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
                                      ATTEMPT_COUNT       NUMBER(10) DEFAULT 0 NOT NULL,
                                      WORKER_ID           VARCHAR2(100 CHAR),
                                      LEASE_UNTIL         TIMESTAMP WITH TIME ZONE,
                                      NEXT_ATTEMPT_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                                      CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                                      PROCESSED_AT        TIMESTAMP WITH TIME ZONE,
                                      FAILURE_CODE        VARCHAR2(100 CHAR),

                                      CONSTRAINT PK_TRANSACTION_REQUESTS PRIMARY KEY (ID),
                                      CONSTRAINT UQ_TRANSACTION_REQUEST_CODE UNIQUE (REQUEST_CODE),
                                      CONSTRAINT UQ_REQUEST_IDEMPOTENCY UNIQUE (CLIENT_ID, IDEMPOTENCY_KEY),
                                      CONSTRAINT FK_REQUEST_SOURCE FOREIGN KEY (SOURCE_ACCOUNT_ID)
                                          REFERENCES ACCOUNTS(ID),
                                      CONSTRAINT FK_REQUEST_DESTINATION FOREIGN KEY (DESTINATION_ACCOUNT_ID)
                                          REFERENCES ACCOUNTS(ID),
                                      CONSTRAINT CK_REQUEST_TYPE CHECK (
                                          TRANSACTION_TYPE IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')
                                          ),
                                      CONSTRAINT CK_REQUEST_STATUS CHECK (
                                          STATUS IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')
                                          ),
                                      CONSTRAINT CK_REQUEST_AMOUNT CHECK (AMOUNT > 0),
                                      CONSTRAINT CK_REQUEST_ATTEMPTS CHECK (ATTEMPT_COUNT >= 0),
                                      CONSTRAINT CK_REQUEST_ACCOUNTS CHECK (
                                          (TRANSACTION_TYPE = 'DEPOSIT'
                                              AND SOURCE_ACCOUNT_ID IS NULL
                                              AND DESTINATION_ACCOUNT_ID IS NOT NULL)
                                              OR
                                          (TRANSACTION_TYPE = 'WITHDRAWAL'
                                              AND SOURCE_ACCOUNT_ID IS NOT NULL
                                              AND DESTINATION_ACCOUNT_ID IS NULL)
                                              OR
                                          (TRANSACTION_TYPE = 'TRANSFER'
                                              AND SOURCE_ACCOUNT_ID IS NOT NULL
                                              AND DESTINATION_ACCOUNT_ID IS NOT NULL
                                              AND SOURCE_ACCOUNT_ID <> DESTINATION_ACCOUNT_ID)
                                          )
);

-- 4. Financial transactions
CREATE TABLE FINANCIAL_TRANSACTIONS (
                                        ID                      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                                        REQUEST_ID              NUMBER(19) NOT NULL,
                                        PARENT_TRANSACTION_ID   NUMBER(19),
                                        TRACKING_CODE           VARCHAR2(64 CHAR) NOT NULL,
                                        TRANSACTION_TYPE        VARCHAR2(20 CHAR) NOT NULL,
                                        AMOUNT                  NUMBER(19,4) NOT NULL,
                                        CREATED_AT              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                                        CONSTRAINT PK_FINANCIAL_TRANSACTIONS PRIMARY KEY (ID),
                                        CONSTRAINT UQ_FINANCIAL_TRACKING_CODE UNIQUE (TRACKING_CODE),
                                        CONSTRAINT FK_FINANCIAL_REQUEST FOREIGN KEY (REQUEST_ID)
                                            REFERENCES TRANSACTION_REQUESTS(ID),
                                        CONSTRAINT FK_FINANCIAL_PARENT FOREIGN KEY (PARENT_TRANSACTION_ID)
                                            REFERENCES FINANCIAL_TRANSACTIONS(ID),
                                        CONSTRAINT CK_FINANCIAL_TYPE CHECK (
                                            TRANSACTION_TYPE IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER', 'FEE')
                                            ),
                                        CONSTRAINT CK_FINANCIAL_AMOUNT CHECK (AMOUNT > 0),
                                        CONSTRAINT CK_FINANCIAL_PARENT CHECK (
                                            PARENT_TRANSACTION_ID IS NULL OR PARENT_TRANSACTION_ID <> ID
                                            )
);

-- 5. Ledger entries
CREATE TABLE LEDGER_ENTRIES (
                                ID                      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                                FINANCIAL_TRANSACTION_ID NUMBER(19) NOT NULL,
                                ACCOUNT_ID              NUMBER(19) NOT NULL,
                                ENTRY_TYPE              VARCHAR2(10 CHAR) NOT NULL,
                                AMOUNT                  NUMBER(19,4) NOT NULL,
                                CREATED_AT              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

                                CONSTRAINT PK_LEDGER_ENTRIES PRIMARY KEY (ID),
                                CONSTRAINT FK_LEDGER_TRANSACTION FOREIGN KEY (FINANCIAL_TRANSACTION_ID)
                                    REFERENCES FINANCIAL_TRANSACTIONS(ID),
                                CONSTRAINT FK_LEDGER_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
                                    REFERENCES ACCOUNTS(ID),
                                CONSTRAINT CK_LEDGER_ENTRY_TYPE CHECK (ENTRY_TYPE IN ('DEBIT', 'CREDIT')),
                                CONSTRAINT CK_LEDGER_AMOUNT CHECK (AMOUNT > 0)
);

-- 6. Account change audit
CREATE TABLE ACCOUNT_AUDIT (
                               ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                               ACCOUNT_ID  NUMBER(19) NOT NULL,
                               CHANGED_BY  VARCHAR2(100 CHAR) NOT NULL,
                               CHANGED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                               FIELD_NAME  VARCHAR2(100 CHAR) NOT NULL,
                               OLD_VALUE   CLOB,
                               NEW_VALUE   CLOB,

                               CONSTRAINT PK_ACCOUNT_AUDIT PRIMARY KEY (ID),
                               CONSTRAINT FK_AUDIT_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
                                   REFERENCES ACCOUNTS(ID)
);

-- Indexes for worker processing and account history
CREATE INDEX IDX_REQUEST_STATUS_RETRY
    ON TRANSACTION_REQUESTS (STATUS, NEXT_ATTEMPT_AT);

CREATE INDEX IDX_REQUEST_SOURCE
    ON TRANSACTION_REQUESTS (SOURCE_ACCOUNT_ID);

CREATE INDEX IDX_REQUEST_DESTINATION
    ON TRANSACTION_REQUESTS (DESTINATION_ACCOUNT_ID);

CREATE INDEX IDX_FINANCIAL_REQUEST
    ON FINANCIAL_TRANSACTIONS (REQUEST_ID);

CREATE INDEX IDX_FINANCIAL_PARENT
    ON FINANCIAL_TRANSACTIONS (PARENT_TRANSACTION_ID);

CREATE INDEX IDX_LEDGER_ACCOUNT_DATE
    ON LEDGER_ENTRIES (ACCOUNT_ID, CREATED_AT);

CREATE INDEX IDX_AUDIT_ACCOUNT_DATE
    ON ACCOUNT_AUDIT (ACCOUNT_ID, CHANGED_AT);
